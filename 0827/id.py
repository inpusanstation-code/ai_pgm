# ==============================================================================
# 1. 불변 객체 (Immutable: 정수, 문자열, 튜플 등)
# - 값이 바뀌지 않는 객체입니다.
# - 파이썬은 메모리 절약을 위해 자주 쓰이는 작은 정수(-5 ~ 256)를 미리 메모리에 만들어 두고 재사용(Interning)합니다.
# ==============================================================================
a = 1000
b = 1000
c = 50
d = 50

# ==============================================================================
# 2. 가변 객체 (Mutable: 리스트, 딕셔너리, 집합 등)
# - 내부 값을 변경할 수 있는 객체입니다.
# - 내용이 똑같더라도 새로 생성할 때마다 메모리에 별도의 새로운 공간을 만듭니다.
# ==============================================================================
list1 = [1, 2, 3]
list2 = [1, 2, 3]

# ------------------------------------------------------------------------------
# [1] 불변 객체 (정수) 비교 출력
# ------------------------------------------------------------------------------
print(f"--- 1. 불변 객체 (정수) 비교 ---")
print(f"변수 a (값: {a})의 ID: {id(a)}")
print(f"변수 b (값: {b})의 ID: {id(b)}")

# == 연산자: 두 변수가 가진 "값"이 같은지 비교합니다.
print(f"a == b 결과: {a == b}")  # True (둘 다 1000으로 값이 같음)

# is 연산자: 두 변수가 "동일한 메모리 주소(ID)"를 가리키는지 비교합니다.
# 1000은 범위(-5 ~ 256) 밖이므로 각각 별개의 메모리 객체로 생성됩니다.
print(f"a is b 결과: {a is b}")  # False (값은 같지만 메모리 주소가 다름)
print("-" * 30)

print(f"변수 c (값: {c})의 ID: {id(c)}")
print(f"변수 d (값: {d})의 ID: {id(d)}")

# 50은 파이썬이 미리 메모리에 만들어 둔 숫자 범위(-5 ~ 256)에 해당합니다.
# 따라서 c와 d는 새로 만들어지지 않고 기존의 동일한 메모리 주소를 공유합니다.
print(f"c is d 결과: {c is d}")  # True (값도 같고 메모리 주소도 같음)
print("=" * 30)

# ------------------------------------------------------------------------------
# [2] 가변 객체 (리스트) 비교 출력
# ------------------------------------------------------------------------------
print(f"--- 2. 가변 객체 (리스트) 비교 ---")
print(f"변수 list1 (값: {list1})의 ID: {id(list1)}")
print(f"변수 list2 (값: {list2})의 ID: {id(list2)}")

# 리스트 안의 내용물(값)이 동일한지 체크합니다.
print(f"list1 == list2 결과: {list1 == list2}")  # True (내용물이 [1, 2, 3]으로 같음)

# 가변 객체는 내용이 같아도 항상 서로 다른 독립된 메모리 공간에 생성됩니다.
print(f"list1 is list2 결과: {list1 is list2}")  # False (독립된 별개의 리스트 객체임)