# 1. 단일 문자열 입력받기
c = input("문자열을 입력 하세요 : ")
print(c)

# 2. 쉼표(,)를 기준으로 나누어 두 변수에 저장하기
# (주의: 사용자가 입력할 때 '10,20' 처럼 콤마로 구분해서 넣어야 합니다.)
a, b = input("문자열 두개 를 입력 하세요 (예: 10,20): ").split(",")
print(a, b)
print(int(a) + int(b))  # 문자열을 정수(int)로 변환하여 더하기 (산술 연산: 30)
print(a + b)            # 문자열 상태로 더하기 (문자열 연결: "1020")

# 3. map()을 활용해 공백 기준 입력과 정수 형변환을 동시에 처리
# (사용자가 입력할 때 '10 20' 처럼 띄어쓰기로 구분해서 넣어야 합니다.)
a, b = map(int, input("문자열 두개 를 입력 하세요 (예: 10 20): ").split())
print(a, b)
print(a + b)

# --- [map() 동작 원리 주석 분석] ---
# ① input("...") : "10 20" (문자열 입력)
# ② .split() : 공백 기준으로 분할 -> ["10", "20"] (문자열 리스트)
# ③ map(int, ...) : 리스트의 모든 요소에 int() 적용 -> int("10"), int("20")
# ④ a, b = ... : 각각 10, 20 정수 형태로 변수 할당

# 4. map() 함수 기본 사용 예제
def double(x):
    return x * 2

numbers = [1, 2, 3, 4, 5]

# numbers의 모든 요소에 double 함수를 적용
result = map(double, numbers)

# map 결과 객체를 리스트 형태로 변환하여 출력: [2, 4, 6, 8, 10]
print(list(result))