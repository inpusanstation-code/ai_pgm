# ==============================================================================
# 1. 함수를 리스트에 담아서 반복문으로 실행하기
# 파이썬에서는 함수도 하나의 값(객체)이므로 리스트의 요소로 넣을 수 있습니다.
# ==============================================================================
def f1(x): return x**2  # 제곱을 구하는 함수
def f2(x): return x**3  # 세제곱을 구하는 함수
def f3(x): return x**4  # 네제곱을 구하는 함수

# 함수 이름(참조)들을 리스트에 저장합니다. (함수를 호출하는 f1()이 아니라 이름만 담음)
li = [f1, f2, f3]

# 리스트 속 함수들을 하나씩 꺼내어 숫자 2를 인자로 넣어 실행합니다.
for i in li:
    print(i(2))  # 1번째: f1(2) -> 4 / 2번째: f2(2) -> 8 / 3번째: f3(2) -> 16

# --- 출력 결과 ---
# 4
# 8
# 16


# ==============================================================================
# 2. lambda(람다) 함수와 리스트 활용
# lambda는 def 키워드 없이 한 줄로 간단하게 함수를 만들 때 사용합니다. (익명 함수)
# 문법: lambda 매개변수: 표현식
#
# ★ [핵심] lambda의 return 특징:
# - lambda는 'return' 키워드를 직접 적지 않아도, 콜론(:) 오른쪽 표현식의 결과를 '자동으로 반환(return)'합니다.
# - 오히려 'return' 키워드를 명시하면 문법 에러(SyntaxError)가 발생합니다.
#   (예: lambda x, y: return x + y -> 에러 발생!)
# ==============================================================================
L = [
    lambda x, y: x**2 + y,  # return x**2 + y 와 동일하게 자동 반환됨
    lambda x, y: x**3 + y,  # return x**3 + y 와 동일하게 자동 반환됨
    lambda x, y: x**4 + y   # return x**4 + y 와 동일하게 자동 반환됨
]

# 리스트 속 람다 함수들을 순서대로 꺼내어 x=3, y=4를 넣고 실행합니다.
for f in L:
    print(f(3, 4))
    # 1번째: 3**2 + 4 = 9 + 4 = 13
    # 2번째: 3**3 + 4 = 27 + 4 = 31
    # 3번째: 3**4 + 4 = 81 + 4 = 85

# --- 출력 결과 ---
# 13
# 31
# 85

# 리스트의 인덱싱을 이용해 특정 위치의 람다 함수만 직접 호출할 수도 있습니다.
# L[0]은 첫 번째 람다 함수(lambda x, y: x**2 + y)를 의미하므로 x=4, y=5를 대입합니다.
print(L[0](4, 5))  # 4**2 + 5 = 16 + 5 = 21

# --- 출력 결과 ---
# 21