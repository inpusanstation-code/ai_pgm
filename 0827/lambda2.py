# ==============================================================================
# 1. lambda 함수를 변수에 할당하여 호출하기
# - lambda x: x * 2 는 "입력받은 x에 2를 곱해 반환하는 함수"입니다.
# - 생성한 람다 함수를 my_module이라는 변수에 저장했습니다.
# ==============================================================================
my_module = lambda x: x * 2

my_module(2)        # 함수를 실행하여 결과 4가 계산되지만, print()가 없어 화면에 출력되지는 않음
print(my_module(2)) # 계산된 결과 4를 화면에 출력 (출력: 4)


# ==============================================================================
# 2. lambda 함수의 즉시 실행 (IIFE: Immediately Invoked Function Expression)
# - 함수를 변수에 담지 않고, 생성하자마자 (함수)(인자) 형태로 즉시 실행할 수 있습니다.
# ==============================================================================
print((lambda x: x * 2)(3)) 
# (lambda x: x * 2) -> "2를 곱하는 함수"를 정의하자마자
# (3)               -> 인자 x=3을 전달하여 즉시 실행! (3 * 2 = 6 출력)


# ==============================================================================
# 3. lambda 함수의 중첩 (클로저 / 고차 함수 형태)
# - 람다 함수 안에 또 다른 람다 함수를 반환하는 구조입니다.
# ==============================================================================
((lambda x: (lambda y: x + y))(99))(2)
# 함수가 계산되어 결과값 101이 구해지지만, print()가 없으므로 화면에 출력되지는 않음

print(((lambda x: (lambda y: x + y))(99))(2))
# 단계별 실행 순서:
# ① (lambda x: ...)(99)   -> x에 99가 대입됩니다.
#                           그 결과 (lambda y: 99 + y) 라는 '새로운 함수'가 반환됩니다.
# ② (새로운 함수)(2)       -> 반환된 함수에 y=2가 대입됩니다.
# ③ 99 + 2                -> 최종 연산 결과인 101이 반환되어 print로 출력됩니다. (출력: 101)