import time
from neuromeka import IndyDCP3  # 뉴로메카 로봇 제어를 위한 IndyDCP3 SDK 모듈 불러오기

# ==========================================
# 1. 로봇 연결 (STEP IP 설정)
# ==========================================
# 제어기(STEP)의 IP 주소를 지정합니다. (실제 환경에 맞게 변경)
step_ip = "192.168.3.4"

# IndyDCP3 인스턴스를 생성하여 로봇 제어기와 통신 연결을 시도합니다.
indy = IndyDCP3(step_ip)

# ==========================================
# 2. Waypoint(경유지) 관절 각도 정의
# ==========================================
# 로봇의 6개 관절(Joint 1~6) 각도를 도(degree) 단위 리스트로 정의합니다.
# [J1, J2, J3, J4, J5, J6]
WAYPOINT1 = [0, 0, -90, 0, -90, 0]
WAYPOINT2 = [-30, 20, -70, 30, -80, -50]
WAYPOINT3 = [30, 10, -60, -20, -70, 40]

# ==========================================
# 3. 이동 완료 확인 함수 (깔끔한 출력 버전)
# ==========================================
def wait_move_done():
    """
    이동 명령 실행 후, 로봇이 목표 위치에 도착할 때까지 대기하는 함수입니다.
    반복 출력 없이 이동 시작/완료 메시지만 깔끔하게 출력합니다.
    """
    # [중요] 제어기가 새 명령을 수신하여 상태를 '이동 중(False)'으로 갱신할 때까지 대기
    time.sleep(0.3)  
    
    # 이동 시작 안내 메시지 (한 번만 출력)
    print(" -> 이동 중...")
    
    while True:
        # 로봇의 실시간 모션 데이터를 가져옵니다.
        motion_data = indy.get_motion_data()
        
        # 'is_target_reached' 필드는 목표지점 도착 여부(True/False)를 반환합니다.
        movedone = motion_data['is_target_reached']
        
        # 목표 지점에 도달했으면 루프를 탈출합니다.
        if movedone:
            break
            
        # CPU 과점유 방지 및 통신 주기를 고려하여 0.1초 대기
        time.sleep(0.1)
        
    print(" -> 이동 완료!")

# ==========================================
# 4. Home 위치 이동
# ==========================================
print("\n[1/5] Home 이동")
indy.move_home()
wait_move_done()

# ==========================================
# 5. Waypoint 1 이동
# ==========================================
print("\n[2/5] Waypoint 1 이동")
# vel_ratio, acc_ratio: 최대 속도/가속도 대비 20% 속도로 안전하게 이동
indy.movej(jtarget=WAYPOINT1, vel_ratio=20, acc_ratio=20)
wait_move_done()

# ==========================================
# 6. Waypoint 2 이동
# ==========================================
print("\n[3/5] Waypoint 2 이동")
indy.movej(jtarget=WAYPOINT2, vel_ratio=20, acc_ratio=20)
wait_move_done()

# ==========================================
# 7. Waypoint 3 이동
# ==========================================
print("\n[4/5] Waypoint 3 이동")
indy.movej(jtarget=WAYPOINT3, vel_ratio=20, acc_ratio=20)
wait_move_done()

# ==========================================
# 8. 다시 Home 이동 및 종료
# ==========================================
print("\n[5/5] Home 복귀")
indy.move_home()
wait_move_done()

print("\n==========================================")
print("모든 Waypoint 이동이 성공적으로 완료되었습니다!")
print("==========================================")